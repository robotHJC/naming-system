/* =========================================================================
 * era-chars.js —— 上代用字表（时代感扣分）
 *
 * 为什么需要这个文件
 * ---------------------------------------------------------------
 * 用户反馈「功能里面有的名字太老气了，比如伟、刚、钢、茂、超」。
 * 查下来是**评分设计上的一个真实缺陷**：
 *
 *   popularity.js 的热度表衡量的是「这个字在**人口**里有多常见」，
 *   而我把它当成了「这个字在**当代起名**里有多时髦」来用。
 *   结果这批字全部落在「现代感」的舒适区（热度 55-91）拿满分：
 *
 *     伟 86 · 刚 86 · 军 86 · 强 86 · 国 85 · 建 85 · 丽 86 ·
 *     艳 86 · 敏 86 · 静 86 · 娟 86 · 燕 86 · 芳 86
 *
 *   但它们的「常见」来自 1950-1990 年代出生的人。
 *   今天给新生儿取名「郝建军」「郝伟刚」，读起来是上一代的语感。
 *   热度表区分不了「谁在用」，所以必须单独补一层「时代感」。
 *
 * 必须说清楚的两件事
 * ---------------------------------------------------------------
 * 1. **这是一张人工判断的表，不是数据。**
 *    「哪个字显老」本质上是审美判断，没有权威公开数据集。
 *    我不打算把它包装成数据驱动 —— 那就是我在编数字。
 *    能做的只有：把判断标准写清楚、让扣分规则透明、用测试锁住行为。
 *
 * 2. **是「降权」不是「禁用」。**
 *    这些字仍然可以被选用、仍然参与五行与音韵评分，只是拿不到
 *    「现代感」的分。理由：
 *      · 有的字并非纯粹老气（「静」在《诗经》「静女其姝」里是好字，
 *        「志」在「志远」里也成立），一刀切禁掉会误伤；
 *      · 长辈可能有自己的偏好，系统不该替他做绝对判断；
 *      · 更实际的原因：如果某个八字的喜用神恰好只对应这类字，
 *        硬禁用会让候选池空掉。
 *
 *    实际效果（因为「现代名字词表」命中会给 +12，足以抵掉扣分）：
 *      志强 = 志(-6) 强(-6) 无词表分 = -12  → 沉到后面
 *      志远 = 志(-6) 远( 0) 词表 +12   =  +6  → 仍能排前
 *      静娟 = 静(-6) 娟(-6) 无词表分 = -12  → 沉到后面
 *      静姝 = 静(-6) 姝( 0) 词表 +12   =  +6  → 仍能排前
 *    也就是说：**机制会自己纠正**——单纯堆老气字会被压下去，
 *    但用这些字组成的真正好搭配不受影响。
 *
 * 这张表按**字**查，与字库来源无关，所以对联网加入的字同样生效：
 * 像「超」「英」「玲」「进」这些内置字库里没有的字，
 * 一旦通过联网扩充进来，一样会被扣分。
 *
 * 收录标准（尽量保守，宁可漏收也不要误伤）
 * ---------------------------------------------------------------
 * 只有同时满足下面两条才收：
 *   (a) 在 1950-1990 年代是取名主流用字；
 *   (b) 今天放进新生儿名字里，大多数人会觉得「这是长辈的名字」。
 * 边界不清的一律不收，理由逐条写在文件末尾的「边界字」注释里。
 * ========================================================================= */
(function (global) {
  'use strict';

  var NS = (global.NS = global.NS || {});

  /* 每个命中字的扣分。定 6 是有依据的：
   *   · 必须明显大于「热度舒适区」最多给到的 6 分（否则字被扣了还是一样高）
   *   · 必须小于「现代名字词表」给的 12 分（否则好搭配会被误杀）
   * 于是形成上面对照里那种「单堆老气字 ↓ / 好搭配 ↑」的分野。 */
  NS.ERA_PENALTY = 6;

  NS.ERA_CHARS = (function () {
    var m = Object.create(null);

    /* ---- 男名：革命 / 建设 / 强壮 那一代的语感 ---- */
    ('军 建 国 民 兴 伟 刚 强 勇 亮 富 贵 荣 发 财 钢 茂 超 学 华 永 德 ' +
      '志 平 兵 武 龙 虎 铁 银 宝 旺 隆 昌 胜 雄 勋 卫 东 红 进 前 立 新'
    ).split(/\s+/).forEach(function (c) { if (c.length === 1) m[c] = 1; });

    /* ---- 女名：同年代主流，今天用显陈旧 ---- */
    ('芳 芬 秀 英 梅 桂 艳 娟 燕 珍 惠 淑 丽 玉 玲 菊 娥 妹 敏 静 萍 ' +
      '凤 霞 珠 翠 红 香 贞 娣 娇 贤 巧'
    ).split(/\s+/).forEach(function (c) { if (c.length === 1) m[c] = 1; });

    return m;
  })();

  /* =========================================================================
   * 边界字：看着像上代用字，但**故意没收**，理由如下。
   * 把理由写在这里而不是只留在脑子里，是因为「哪个字显老」是判断，
   * 判断就该能被审视 —— 谁不同意，可以直接对着这段说。
   *
   *   兰 —— 兰花古今通用，且「兰芷」「兰若」「若兰」都是好搭配。
   *         收了它会把女名测试里的第 1 名一起打下去，属于误伤。
   *   明 —— 「明轩」「明远」「明哲」当代仍在大量使用，不是年代感。
   *   文 —— 书卷气而非年代感：「文轩」很现代，「学文」才老，
   *         而「学」已经单独收录了。
   *   静 —— **收进来了**，这里单独说明原因，因为它最容易引起争议。
   *         它出自《诗经》「静女其姝」，看着像雅字；
   *         但实测「静」是老气组合的常客（静娟 / 静芬 / 静兰 / 静茹），
   *         而当代真正在用的「静姝」「静宜」有词表 +12 兜着，
   *         收了不会误杀。判据是「实际搭配」而不是「字本身雅不雅」。
   *   秋 冬 —— 季节意象，无年代属性（「栗冬」是当代审美）。
   *   云 月 雪 雨 风 花 春 —— 同上，自然意象。
   *         我第一版把这些字全收进来了，是想当然，
   *         实测会把大量好名字误伤，已全部撤掉。
   *         （「花」在女名那行末尾漏删过一次，被测试抓出来了 ——
   *          这条断言现在还在，就是为了拦住同类漏网。）
   *   秀 — 边界字，最终保留：「郝秀兰」「郝秀英」是典型的老气组合；
   *         而「秀言」有词表 +12 兜着，不会被误杀。
   *   玉 — 同「秀」，保留（「郝玉芬」读起来明显是上一代）。
   *   珍 — 同「秀」，保留。
   *   平 — 同「秀」，保留（「建平」「小平」的年代感太典型）。
   * ========================================================================= */

  /** 用字是否偏上一代风格 */
  NS.isEraChar = function (ch) {
    return NS.ERA_CHARS[ch] === 1;
  };

  /** 一组用字里有多少个上代用字 */
  NS.eraHitCount = function (chars) {
    var n = 0;
    (chars || []).forEach(function (c) { if (NS.ERA_CHARS[c] === 1) n++; });
    return n;
  };

})(typeof window !== 'undefined' ? window : globalThis);
