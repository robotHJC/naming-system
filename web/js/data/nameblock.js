/* =========================================================================
 * nameblock.js —— 「整名是个常用词」的降权表
 *
 * 为什么需要它
 * ---------------------------------------------------------------
 * 实测出来的真问题（走查 6 个姓氏 × 3 性别、统计前 20 名）：
 *   360 个前 20 名里有 9 个是**日常词**，而且位置很靠前 ——
 *     郝博士 第3名　李博士 第3名　王博士 第6名　陈博士 第6名
 *     张博士 第8名　刘博士 第20名　郝斯文 第10名　陈斯文 第14名
 *     「博士」几乎对每个姓氏都进前 3-8 名。
 *
 * 根因不是「没查谐音」，而是**出处机制在反向奖励它**：
 * 「博士」是唐代真实官职（国子博士、太学博士），在《唐诗三百首》里
 * 确实相邻出现过，于是被判为「出处成词」+6 分 ——
 * 专门用来找典故的机制，把「博士」当成了典故。
 *
 * 单看每个字都没问题：博（热度 89，舒适区）、士（热度 70，舒适区）、
 * 五行水金、声调错落、三才土土土大吉。**逐字判据全过，问题出在整名上。**
 *
 * 所以这里按**整名**查，与 data/era-chars.js 同一套思路：
 * 人工判断表 + 写清依据 + 是降权不是禁用。
 *
 * 收录标准（这条线很重要，别放宽）
 * ---------------------------------------------------------------
 * 只收**读起来像"词"而不像"名"**的：
 *   称谓/职务、现代器物、现代抽象名词、食物、动物、身体部位、贬义词
 *
 * **刻意不收**的（它们也是常用词，但作为名字是好的）：
 *   安然 安宁 清和 若水 明月 清风 秋月 嘉树 云舒 知微 景明 星河 山水
 *   —— 这些是**雅词/意象**，用它们取名是传统做法；
 *   而那些被收进来的，问题不在于"是个词"，而在于那个词**指称的是
 *   某个具体身份、物品或概念**，套在人名上就变成了笑话或误会。
 * 换句话说：**判断标准不是"是不是词"，而是"作为名字会不会让人出戏"。**
 *
 * 这只是抽样覆盖，不是穷举 —— 现代汉语常用词有几万个，
 * 穷举需要一份权威词表（且要人工逐条判断适不适合当名字）。
 * 现在的表覆盖的是实测中真正出现过、以及最容易被自动拼出来的那些。
 * ========================================================================= */
