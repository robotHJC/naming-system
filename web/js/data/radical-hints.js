/* =========================================================================
 * radical-hints.js —— 部首推荐用的两张对照表
 *
 * 两张表的性质完全不同，界面上必须分开呈现，不能混为一谈：
 *
 *   一、五行 → 部首：见 core/radical.js 的 wuxingMap()
 *       不在这里写死。因为字库各偏旁组的五行并不都齐：
 *         全齐（100%）：氵木艹钅日山土雨竹刂冫鸟贝禾彳辶囗
 *         将近齐：王 96%（瑛 是土）、火 93%（然 是金）
 *         混　杂：女 78%、忄 67%、宀 50%、亻 44%、口 40%
 *       硬写一张表就会出现「喜用神是土 → 建议单人旁」这种
 *       在数据上站不住脚的推荐（实测时就是这么错的）。
 *       所以改为从字库实时推导，只保留主导五行占比 ≥90% 的分组。
 *
 *   二、生肖 → 宜用部首（民俗，仅供参考）
 *       这是民间姓名学的通俗说法，**没有经典出处，各家说法也不一致**。
 *       典型逻辑是取象：属马要吃草（艹）、要有屋檐（宀）、要能跑（辶）；
 *       属鼠要有洞（宀）、有粮（禾 米）。
 *       本表只收录字库里真实存在的偏旁分组，并在界面上明确标为「民俗参考」。
 *       系统**不会**自动应用它 —— 必须用户自己点了才会生效，
 *       而且它的优先级低于八字喜用神（面板里会写明）。
 * ========================================================================= */
(function (global) {
  'use strict';

  var NS = (global.NS = global.NS || {});

  /* ---------------- 五行 → 部首：不硬编码 ----------------
   * 用 NS.Radical.wuxingMap() 从字库实时推导，原因见文件头。
   * 引用这个常量只是为了兼容旧代码与阅读方便。 */
  Object.defineProperty(NS, 'WUXING_RADICALS', {
    configurable: true,
    get: function () {
      if (!NS.Radical || !NS.Radical.wuxingMap) return null;
      var m = NS.Radical.wuxingMap();
      var out = {};
      Object.keys(m).forEach(function (wx) {
        out[wx] = m[wx].map(function (x) { return x.name; });
      });
      return out;
    }
  });

  /* ---------------- 生肖 → 宜用部首（民俗，仅供参考） ---------------- */
  NS.ZODIAC_RADICALS = {
    '鼠': ['宀', '禾', '亻'],
    '牛': ['艹', '宀', '禾'],
    '虎': ['山', '木', '宀', '王', '氵'],
    '兔': ['艹', '木', '宀'],
    '龙': ['氵', '日', '雨', '王', '宀'],
    '蛇': ['艹', '木', '宀'],
    '马': ['艹', '宀', '木', '禾', '辶'],
    '羊': ['艹', '木', '宀'],
    '猴': ['木', '山', '宀', '王'],
    '鸡': ['宀', '禾', '山'],
    '狗': ['亻', '宀', '山'],
    '猪': ['宀', '禾', '木']
  };

  /* 界面上的「常用部首」顺序：按字库内字数从多到少，排在前面的选择空间大 */
  NS.RADICAL_PICKER_ORDER = [
    '艹', '氵', '木', '王', '日', '钅', '火', '山', '土', '亻',
    '雨', '宀', '辶', '女', '心', '忄', '竹', '口', '讠', '刂'
  ];

})(typeof window !== 'undefined' ? window : globalThis);
