/* =========================================================================
 * namefilter.js —— 「不宜入名」的单字表
 *
 * 为什么需要它
 * ---------------------------------------------------------------
 * 引入《新华字典》（2.1 万字）当用字来源之后，实测出来的真问题：
 * 让「有依据」的字进候选池（一级常用字 或 诗词里出现过）、
 * 按热度排序取前 400 个，池子长这样：
 *
 *   安岸凹奥巴叭扒把白百办半邦包抱悲本比彼币必边便别宾丙不布
 *   残灿仓草册岑层曾朝车澈琛宸晨承诚澄尺斥仇丑出初楚处床吹春…
 *
 * 一半是好字，一半是「凹叭扒把办半抱悲不布斥仇丑出吹」。
 * 逐字看每个都没毛病 —— 常用字、拼音正常、笔画不多，
 * 现有的每一道自动判据都拦不住：
 *   「不」在诗词里出现次数极高、是一级常用字、热度 55；
 *   「把」「办」「抱」同理。**高频 ≠ 适合当名字。**
 *
 * 这类字的共同点是「它们是语法词、日常动作词或器物词」，
 * 而不是「意象」。判断这一点需要语义知识，统计量代替不了，
 * 所以只能人工列表 —— 与 data/era-chars.js、data/nameblock.js 同一套做法。
 *
 * 与 nameblock.js 的分工
 * ---------------------------------------------------------------
 *   nameblock.js        管**整名**是常用词（博士、斯文）→ 降权 16 分
 *   era-chars.js        管**单字**年代感过时（氏、卿、佾）→ 降权 6 分/字
 *   namefilter.js（本文件）管**单字**根本不该进名字 → 直接从候选池剔除
 * 前两个是「扣分」，因为那些字凑巧也能用；本文件是「剔除」，
 * 因为「凹」「叭」「办」无论跟谁配都不像名字，留在池里只是占位置。
 *
 * 收录标准（这条线很重要，别放宽）
 * ---------------------------------------------------------------
 * 收：语法词（虚词/代词/连词/介词/副词）、否定词、日常动作动词、
 *     日常器物与生活名词、身体部位、亲属与身份泛称、贬义与消极字、
 *     不能单独成象的时间/数量/方位字、纯数字。
 *
 * **刻意不收**（看着像上面几类，其实是好名字用字；实测踩过这些坑）：
 *   意象名词  山水云雪雨风月星花草木竹松鹤鹿鱼鸟泉岸洲渚
 *   抽象雅词  知 思 念 怀 慕 望 归 安 和 宁 清 澈 澄 朗 承 诚 定 立
 *   传统用字  之 子 其 若（王羲之、林若）千 万 百 一 三（马千里）
 *   身份/器物 军 兵 商 官 城 庄 田 楼 桥 路 门 户 友 主 曾 开 关 飞
 *              （建军、张路、飞 都是真在用的名字用字）
 *   判断标准：**这个字放进「李X」里，别人会不会以为你写错了。**
 *   会 → 收。只是不时髦 → 交给 era-chars.js 去降权。
 *
 * 覆盖面
 * ---------------------------------------------------------------
 * 这是**高频污染字**的清单，不是穷举 —— 2.1 万字里还有一些
 * （尤其二级字表的日用字）没盖到。但实测接进「按部首找字」与
 * 「整本字典取名」两条路后，候选池与生成结果里都不再出现这类字。
 * 后续要补，判断标准照上面那条线走。
 * ========================================================================= */
(function (global) {
  'use strict';
  var NS = (global.NS = global.NS || {});

  /* 分组只为了可读与可维护 —— 值会保留下来，
   * 界面上可以据此告诉用户「这个字为什么没被推荐」。
   * 每组说明就是收录理由，改动时请一并更新。 */
  var GROUPS = {
    /* 虚词 / 代词 / 连词 / 介词 / 副词 —— 「李而」「李乎」「李则」 */
    '语法词': '不兮而乎矣焉哉耶也者之其以为或与且乃亦则所尔汝吾我' +
      '谁何那这此彼他它自各每某皆尽只但却更又还就才再很太最都已' +
      '将把被给让使由往及并虽故因既况夫盖岂弗勿毋到比便曾独别在是',

    /* 否定 / 禁戒 —— 「李无」「李莫」「李未」 */
    '否定词': '无莫未非否免',

    /* 日常动作 —— 「李吹」「李抱」「李起」 */
    '动作动词': '吃喝说看听拿放打买卖走跑睡坐站叫喊找想认觉试受问' +
      '求要得该能会敢请谢帮换变做干写读唱跳停等送带提拉推举抬搬用' +
      '教讲谈算记忘怕累哭骂吵闹偷抢骗扔丢捡爬掉挂撞碰掐拧拽摔跌藏' +
      '躲逃拦挡逗欺抱起烧消吹来归',

    /* 名词 / 形容词里「不能单独成象」的那批 —— 实测占掉候选池名额最多的就是它们 */
    '非意象名词': '公今木火内气切五夭引布处古旧末目鸟去石市台头外未' +
      '存地多共合回众低角连声识纵服昏径卷空命奈朋往物炙度宫故挂徊' +
      '食室首挑昼宾匪离眠索毫徘排梢淘欲溅啼感鼓楼蓦阙塞睡磋麾醒流' +
      '好关皇浪鸠生',

    /* 日常器物 / 生活场所 —— 「李床」「李灯」「李墙」 */
    '器物名词': '钱饭菜车床灯桌椅纸笔锅碗杯盘刀枪炮弹衣裤鞋帽袋箱' +
      '窗墙屋灶盆桶勺筷罐缸绳钉锤锁伞扇票账债税费价街巷村庄镇店厂' +
      '矿井沟渠坝房院尺酒帘炉茴',

    /* 身体 / 生理 —— 这类字套在人名上最「出戏」 */
    '身体生理': '头脸眼耳鼻嘴牙舌手脚腿肚背腰血骨肉皮毛喉颈肩膝肘' +
      '腹胸胆胃肝肺肾肠汗泪尿屎屁痰脓疮疤痘痣瘤',

    /* 亲属 / 身份 / 泛称 —— 「李哥」「李妈」「李员」 */
    '称谓泛称': '爸妈哥姐弟妹爷奶叔姨舅姑婶嫂崽娃妮朋友伴侣客邻伙' +
      '群队员工匪贼犯囚奴仆佣农匠徒吏差役',

    /* 贬义 / 消极 —— 这一组最不能漏，漏一个就是「李悲到」 */
    '贬义消极': '悲恨苦病痛死亡杀伤仇丑歹残破败输罪恶灾祸烦累穷困' +
      '溃崩毒凶难愁衰朽腐烂臭脏乱罚刑狱疾疫疯傻蠢笨弱懦卑贱贫愚痴' +
      '拙钝毁焚殃孽冤妒羞辱耻慌恐惧怖惊骇忧闷燥躁虐暴蛮横歪斜瘫瘸' +
      '瞎聋哑凋寂枯',

    /* 时间 / 数量 / 方位 —— 「李昨」「李层」「李间」 */
    '时间数量方位': '昨年日时分秒号刻前后边旁上下左右里外内间半满些' +
      '个只条块件双对层批次回遍顿阵堆排列串束颗颗粒滴幅页段末尾底' +
      '顶侧沿端尽',

    /* 纯数字 —— 没有意象可言 */
    '数字': '二四六七八九十零两几壹贰叁肆伍陆柒捌玖拾',

    /* 叹词 / 拟声 —— 字形本身就破碎 */
    '叹词拟声': '啊呀哎唉哦噢喔咦嗯嘿哈嘻呵哟呦哇啪哗咚铛叮砰唔呃嘶' +
      '吱叽咕嘟吧吗呐'
  };

  /* 拼成一个字符集；去空格、去重复。 */
  var SET = Object.create(null);
  var LIST = '';
  Object.keys(GROUPS).forEach(function (k) {
    var s = GROUPS[k].replace(/\s+/g, '');
    for (var i = 0; i < s.length; i++) {
      var ch = s.charAt(i);
      if (SET[ch]) continue;
      SET[ch] = k;          /* 值保留分组名，界面可以解释「为什么不宜入名」 */
      LIST += ch;
    }
  });

  NS.NAME_BLOCK_CHARS = LIST;
  NS.NAME_BLOCK_SET = SET;
  NS.NAME_BLOCK_GROUPS = GROUPS;

  /**
   * 这个字是否不宜入名。
   * @param {string} ch 单字
   * @returns {{blocked:boolean, reason:string}} reason 是分组名，未命中为空串
   */
  NS.nameCharBlock = function (ch) {
    var why = ch ? SET[ch] : null;
    return { blocked: !!why, reason: why || '' };
  };
})(typeof window !== 'undefined' ? window : globalThis);
