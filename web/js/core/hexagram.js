  /**
   * 由姓名笔画起卦
   * @param {number} surnameStrokes 姓氏康熙笔画之和
   * @param {number} givenStrokes   名字康熙笔画之和
   * @returns {Object|null}
   */
  NS.castNameHexagram = function (surnameStrokes, givenStrokes) {
    var s = Number(surnameStrokes), g = Number(givenStrokes);
    if (!isFinite(s) || !isFinite(g) || s <= 0 || g <= 0) return null;

    /* 余 0 作 8 —— 与先天八卦数 1..8 对应 */
    var upperNo = s % 8 || 8;
    var lowerNo = g % 8 || 8;
    var total = s + g;
    var moving = total % 6 || 6;      /* 1..6，自下往上 */

    var upper = NS.BAGUA[upperNo];
    var lower = NS.BAGUA[lowerNo];
    if (!upper || !lower) return null;

    /* 本卦六爻：下卦三爻（初二三）+ 上卦三爻（四五六） */
    var yao = lower.yao.concat(upper.yao);

    /* 变卦：把动爻那一爻阴阳互换 */
    var changed = yao.slice();
    changed[moving - 1] = changed[moving - 1] ? 0 : 1;
    var cLowerNo = baguaFromYao(changed.slice(0, 3));
    var cUpperNo = baguaFromYao(changed.slice(3, 6));

    var nameKey = upperNo + '-' + lowerNo;
    var full = NS.HEXAGRAM_NAMES[nameKey] || ['（未收录）', ''];
    var cFull = cUpperNo && cLowerNo
      ? (NS.HEXAGRAM_NAMES[cUpperNo + '-' + cLowerNo] || ['（未收录）', ''])
      : null;

    /* 体用：动爻所在卦为「用」，另一卦为「体」。
     * 动爻 1-3 在下卦 → 下卦为用、上卦为体；4-6 则相反。 */
    var movingInLower = moving <= 3;
    var tiNo = movingInLower ? upperNo : lowerNo;
    var yongNo = movingInLower ? lowerNo : upperNo;
    var ti = NS.BAGUA[tiNo], yong = NS.BAGUA[yongNo];
    var relation = scoreRelation(ti.wuxing, yong.wuxing);

    return {
      /* 起卦依据，原样回传便于界面展示与用户复核 */
      basis: {
        surnameStrokes: s,
        givenStrokes: g,
        total: total,
        upperNo: upperNo,
        lowerNo: lowerNo,
        moving: moving,
        movingInLower: movingInLower,
        rule: '上卦=姓笔画%8（余0作8）　下卦=名笔画%8（余0作8）　' +
          '动爻=总笔画%6（余0作6）'
      },
      upper: { no: upperNo, name: upper.name, symbol: upper.symbol,
        wuxing: upper.wuxing, image: upper.image, nature: upper.nature },
      lower: { no: lowerNo, name: lower.name, symbol: lower.symbol,
        wuxing: lower.wuxing, image: lower.image, nature: lower.nature },
      name: full[0],
      meaning: full[1],
      yao: yao,
      changedYao: changed,
      changed: cFull ? {
        upper: NS.BAGUA[cUpperNo], lower: NS.BAGUA[cLowerNo],
        name: cFull[0], meaning: cFull[1]
      } : null,
      ti: { name: ti.name, symbol: ti.symbol, wuxing: ti.wuxing, image: ti.image },
      yong: { name: yong.name, symbol: yong.symbol, wuxing: yong.wuxing,
        image: yong.image },
      relation: relation,

      /* 便于界面统一渲染六爻的图形（自下往上画，展示时倒序） */
      symbol: upper.symbol + lower.symbol,

      /* 必须一并展示的免责说明，不要把上面任何一项说成定论 */
      disclaimer: '姓名卦是梅花易数与姓名学的**民俗做法**，' +
        '不是《周易》原书用法（原书以蓍草起卦问事）。' +
        '各家取卦法也不一致，本系统采用的是：' + '上卦取姓笔画、下卦取名笔画、' +
        '动爻取总笔画。吉凶按**体用生克**定（体为不动之卦、用为动爻之卦），' +
        '属民俗流派，仅供参考；与八字喜用神冲突时**以八字为准**。'
    };
  };

