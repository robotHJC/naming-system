/* =========================================================================
 * nayin.js —— 六十甲子纳音
 *
 * 为什么需要它
 * ---------------------------------------------------------------
 * 用户问：「今年马年是火年，那么是否就不能使用带水的字，更不能带火的字？」
 *
 * 这个例子恰好说明**一句话规则不可靠**：
 *   2026 是丙午年 —— 按干支看，丙火 + 午火，确实是「火年」；
 *   但丙午的**纳音**是「天河水」，属**水**。
 *   同一年，两套体系给出相反的五行。
 *
 * 所以系统不能只把干支五行当成「今年属什么」告诉用户 ——
 * 得把两套标注清楚并列出来，让用户看到它们本来就会打架。
 *
 * 关于这张表
 * ---------------------------------------------------------------
 * 六十甲子纳音是**固定查表**，不是推算出来的：六十个干支两两一组，
 * 共 30 组、每组一个纳音名。所以这份数据可核对、不含解释空间 ——
 * 这也是本项目里少数几个「不存在流派争议」的数据之一。
 *
 * 用处：姓名学里常拿年柱纳音当「本命五行」讲（如「天河水命」），
 * 它和年柱干支五行、和八字喜用神是三套不同的口径，必须分开标注。
 *
 * 注意：纳音在**正统八字里基本不用**，它主要出现在民俗命理与
 * 合婚、择日等场景。所以系统把它作为**参考信息**展示，
 * **不参与喜用神判断**，也不参与取名打分。
 * ========================================================================= */
