  /* ------------------------------------------------------------------
   * 解析：与 Python 版 `_parse_chars` 行为一致
   * ------------------------------------------------------------------ */
  function parseChars(rawList) {
    var db = Object.create(null);
    for (var i = 0; i < rawList.length; i++) {
      var line = String(rawList[i]).trim();
      if (!line || line.charAt(0) === '#') continue;
      var p = line.split('|');
      if (p.length !== 8) continue;
      var ch = p[0];
      if (db[ch]) continue; /* 先出现的优先 */
      /* 拼音规范化：Python 用 lu: 表示 lü，这里统一为 ü 便于显示与切分 */
      var py = p[1].trim().replace(/u:/g, 'ü');
      db[ch] = {
        char: ch,
        pinyin: py,
        tone: parseInt(p[2], 10),
        wuxing: p[3],
        gender: p[4],
        styles: p[5].split(',').map(function (s) { return s.trim(); })
          .filter(Boolean),
        meaning: p[6],
        strokes: parseInt(p[7], 10)
      };
    }
    return db;
  }

