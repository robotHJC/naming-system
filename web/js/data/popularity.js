  NS.HEAT = (function () {
    var m = Object.create(null);
    NS.RAW_HEAT.forEach(function (line) {
      var p = line.split('|');
      if (p.length !== 2) return;
      var v = parseInt(p[1], 10);
      if (!isFinite(v) || v <= 0) return;        /* 过滤占位项 */
      if (!/^[\u4e00-\u9fff]$/.test(p[0])) return;
      if (m[p[0]] === undefined) m[p[0]] = v;    /* 先出现优先 */
    });
    return m;
  })();

