  /**
   * 体用生克定吉凶。
   *
   * 「体」= 不动的那一卦（代表自己），「用」= 动爻所在那一卦（代表所遇之事）。
   * 这是梅花易数的定法，规则明确、可复算，但属于**民俗流派**。
   */
  function scoreRelation(tiWx, yongWx) {
    if (!tiWx || !yongWx) return null;
    if (tiWx === yongWx) {
      return { level: '吉', kind: '体用比和', why: '体用同属' + tiWx +
        '，同气相求，无相克之忧' };
    }
    if (SHENG[yongWx] === tiWx) {
      return { level: '吉', kind: '用生体', why: '用（' + yongWx + '）生体（' +
        tiWx + '），外力来助' };
    }
    if (KE[tiWx] === yongWx) {
      return { level: '小吉', kind: '体克用', why: '体（' + tiWx + '）克用（' +
        yongWx + '），能制其事，但需费力' };
    }
    if (SHENG[tiWx] === yongWx) {
      return { level: '平', kind: '体生用', why: '体（' + tiWx + '）生用（' +
        yongWx + '），气往外泄，耗费而少得' };
    }
    return { level: '凶', kind: '用克体', why: '用（' + yongWx + '）克体（' +
      tiWx + '），所遇之事反来相制' };
  }

